"""Write config/manifests/de-gesetze-im-internet.yaml from the laws already downloaded into the cache."""

from __future__ import annotations

import re

import yaml

from ulis.settings import REPO_ROOT

CACHE = REPO_ROOT / "var" / "sources" / "www.gesetze-im-internet.de"
OUT = REPO_ROOT / "config" / "manifests" / "de-gesetze-im-internet.yaml"
HEADER = """# German federal laws fetched from Gesetze im Internet (one xml.zip per law, current consolidation).
# Free use and re-use of the German-language norms (site home page); § 5 Abs. 1 UrhG.
# `abbr` is the law's path on the site (https://www.gesetze-im-internet.de/<abbr>/xml.zip), as listed
# in https://www.gesetze-im-internet.de/gii-toc.xml. Generated by scripts/build_gii_manifest.py from the
# laws downloaded by scripts/bulk_fetch_gii.py.
"""


def main() -> int:
    toc = (CACHE / "gii-toc.xml").read_text(encoding="utf-8", errors="replace")
    titles = {
        abbr: t
        for t, abbr in re.findall(
            r"<title>(.*?)</title>\s*<link>https?://www\.gesetze-im-internet\.de/([^/<>]+)/xml\.zip</link>", toc, re.S
        )
    }
    first = ["gg", "bgb", "stgb", "zpo", "stpo", "hgb", "vwvfg", "bdsg_2018", "kschg", "gewstg"]
    present = sorted(p.parent.name for p in CACHE.glob("*/xml.zip") if p.read_bytes()[:4] == b"PK\x03\x04")
    ordered = [a for a in first if a in present] + [a for a in present if a not in first]
    laws = [
        {"abbr": a, "title": re.sub(r"\s+", " ", titles.get(a, a)).replace("&quot;", '"').replace("&amp;", "&").strip()}
        for a in ordered
    ]
    manifest = {
        "schema_version": 1,
        "source_id": "de-gesetze-im-internet",
        "base_url": "https://www.gesetze-im-internet.de",
        "user_agent": "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)",
        "crawl_delay_seconds": 5,
        "laws": laws,
    }
    OUT.write_text(HEADER + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print(f"{len(laws)} laws in the manifest")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Write docs/corpus.md from the source registry (config/sources), so the list of what is loaded is never hand-kept.

python scripts/generate_corpus_doc.py
"""

from __future__ import annotations

import re
from datetime import date

from ulis.catalog import Catalog
from ulis.settings import REPO_ROOT, load_settings

OUT = REPO_ROOT / "docs" / "corpus.md"


def one_line(text: str | None, limit: int) -> str:
    flat = re.sub(r"\s+", " ", (text or "").strip()).replace("|", "/")
    if len(flat) <= limit:
        return flat
    cut = flat[:limit].rsplit(" ", 1)[0]
    return cut + " ..."


def first_sentence(text: str | None, limit: int) -> str:
    flat = re.sub(r"\s+", " ", (text or "").strip())
    match = re.match(r"(.+?[.;])(\s|$)", flat)
    return one_line(match.group(1) if match else flat, limit)


def main() -> int:
    catalog = Catalog.load(load_settings().config_dir)
    sources = sorted(catalog.sources.sources.values(), key=lambda s: (",".join(s.jurisdictions), s.id))
    active = [s for s in sources if s.status == "active"]
    blocked = [s for s in sources if s.status != "active"]
    lines = [
        "# What is loaded, and what is not",
        "",
        f"Generated by `scripts/generate_corpus_doc.py` from `config/sources/` on {date.today().isoformat()};",
        "do not edit by hand.",
        "",
        f"{len(active)} sources are active: the licence gate lets `ulis.cli ingest` and `load-all` load them.",
        f"{len(blocked)} are recorded as `planned` or `rejected` with the publisher's own findings (a robots.txt that",
        "closes the site, an API key, a licence that forbids reuse, no machine-readable form).",
        "The law itself is public; what blocks a source is the access policy or terms of the website that publishes",
        "it. Nothing is worked around. ULIS covers only what is listed here and makes no claim of completeness.",
        "Research aid, not legal advice.",
        "",
        f"## Active sources ({len(active)})",
        "",
        "| Source | Jurisdictions | Content | Languages | Licence |",
        "|---|---|---|---|---|",
    ]
    for s in active:
        lines.append(
            f"| `{s.id}` | {', '.join(s.jurisdictions)} | {first_sentence(s.coverage, 170)} | "
            f"{', '.join(s.languages)} | {one_line(s.licence.name, 90)} |"
        )
    lines += [
        "",
        f"## Not loaded ({len(blocked)})",
        "",
        "Drafts of permission requests are in [permission-requests.md](permission-requests.md).",
        "",
        "| Source | Status | Jurisdictions | Publisher | Why (licence or access finding) |",
        "|---|---|---|---|---|",
    ]
    for s in blocked:
        lines.append(
            f"| `{s.id}` | {s.status} | {', '.join(s.jurisdictions)} | {one_line(s.publisher, 60)} | "
            f"{one_line(s.licence.name, 150)} |"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(active)} active, {len(blocked)} not loaded -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Write config/manifests/pl-eli-sejm.yaml: every Polish statute (ustawa) that has a current consolidated text.

    python -m scripts.build_eli_manifest

The list comes from the Sejm's ELI API itself (https://api.sejm.gov.pl/eli, no robots.txt, no stated terms; see
config/sources/pl-eli-sejm.yaml):

* ``GET /acts/search?publisher=DU&type=Obwieszczenie&title=jednolitego tekstu ustawy`` pages through every
  announcement (obwieszczenie) of a consolidated text of an ustawa, in force or not (about 5 000 records,
  11 requests of 500). Each record says which act it consolidates (``references["Tekst jednolity dla aktu"]``),
  its legal-status date, whether the API offers HTML (``textHTML``) and whether it is the text in force today.
* An act is listed when one of its consolidated texts is in force today (``inForce`` = IN_FORCE) - "an ustawa
  with a current tekst jednolity". The instrument's text is its newest consolidated text for which the API offers
  HTML (PDF is never parsed). When a newer text exists only as PDF the act is still listed with the older HTML
  text and the entry says so (the parser reports the newer text as an outstanding change).
* The six instruments of the first pilot keep their hand-chosen entries (two successive texts, so that the
  history they show stays reproducible); every other act has its newest HTML text only.

The Constitution (DU/1997/483) is offered by the API as PDF only (``textHTML`` false) and is listed in the header
as not ingestible, not in ``instruments``.

Requests go through PoliteHttp (identifying User-Agent, 5 s apart, cached under var/sources/api.sejm.gov.pl/).
"""

from __future__ import annotations

import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from ulis.sources.connectors.polite_http import PoliteHttp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "pl-eli-sejm.yaml"
CACHE = ROOT / "var" / "sources"
BASE = "https://api.sejm.gov.pl/eli"
USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
PAGE = 500
# The pilot's hand-chosen instruments (key, act, two successive HTML texts); kept exactly.
PILOT = [
    {"key": "kc", "title": "Kodeks cywilny", "act": "DU/1964/93", "consolidated": ["DU/2023/1610", "DU/2024/1061"]},
    {"key": "kk", "title": "Kodeks karny", "act": "DU/1997/553", "consolidated": ["DU/2022/1138", "DU/2024/17"]},
    {
        "key": "uodo",
        "title": "Ustawa o ochronie danych osobowych",
        "act": "DU/2018/1000",
        "consolidated": ["DU/2019/1781"],
    },
    {"key": "kp", "title": "Kodeks pracy", "act": "DU/1974/141", "consolidated": ["DU/2022/1510", "DU/2023/1465"]},
    {
        "key": "kpa",
        "title": "Kodeks postępowania administracyjnego",
        "act": "DU/1960/168",
        "consolidated": ["DU/2023/775", "DU/2024/572"],
    },
    {
        "key": "kro",
        "title": "Kodeks rodzinny i opiekuńczy",
        "act": "DU/1964/59",
        "consolidated": ["DU/2020/1359", "DU/2023/2809"],
    },
]
HEADER = """\
# Polish statutes (ustawy) fetched from the Sejm's ELI API (https://api.sejm.gov.pl/eli), the machine interface to the
# Dziennik Ustaw (Journal of Laws). Generated by `python -m scripts.build_eli_manifest` from the API's own search
# (GET /acts/search?publisher=DU&type=Obwieszczenie&title=jednolitego tekstu ustawy), read on {read_on}.
#
# Scope: every ustawa for which an announcement of a consolidated text (tekst jednolity, obwieszczenie of the Marszałek
# Sejmu under art. 16 of the Act of 20 July 2000 on the publication of normative acts) is IN FORCE today ({n_current}
# acts), minus the {n_nohtml} whose consolidated texts the API offers as PDF only. {n_listed} instruments are listed:
# the {n_pilot} pilot instruments (two successive texts each, one for the data protection act) and {n_new} acts with
# their newest HTML text. {n_stale} of the listed acts have a newer consolidated text that the API offers only as PDF
# (it is reported as an outstanding change, never parsed); their wording is the newest HTML text.
#
# For each instrument the connector fetches the metadata record of the listed consolidated text
# (GET /acts/DU/<year>/<pos>), its HTML (.../text.html) and the metadata record of the act itself, from which the later
# amending acts and the later consolidated texts are reported as outstanding changes. That is {requests} requests at
# 5 s = {hours:.1f} hours for the whole manifest. PDF is never parsed. Texts are listed oldest first; the connector
# checks that their stated legal-status dates strictly increase and refuses anything else.
#
# The Constitution (Dz.U. 1997 nr 78 poz. 483) is offered as PDF only (textHTML false) and cannot be listed. Acts that
# are in force but have no consolidated text (never amended, or not yet consolidated) are not listed: their own
# text.html is the text as announced. To widen, add an `instruments` entry (act + consolidated texts) or change the
# rules in scripts/build_eli_manifest.py. Polish law texts are not protected by copyright (Prawo autorskie art. 4
# pts 1-2); see config/sources/pl-eli-sejm.yaml for the terms, the API documentation and robots.txt findings.
"""


def fetch_json(http: PoliteHttp, url: str, key: str) -> dict[str, Any]:
    got = http.get(url, cache_key=key, headers={"Accept": "application/json"})
    if got is None:
        raise SystemExit(f"{url}: not found")
    return json.loads(got[0].decode("utf-8"))  # type: ignore[no-any-return]


def all_announcements(http: PoliteHttp) -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    offset = 0
    while True:
        url = (
            f"{BASE}/acts/search?publisher=DU&type=Obwieszczenie&title=jednolitego+tekstu+ustawy"
            f"&limit={PAGE}&offset={offset}"
        )
        page = fetch_json(http, url, f"eli/search/tj-ustawy-{offset}.json")
        items.extend(page["items"])
        offset += PAGE
        if offset >= page["totalCount"]:
            return items


def title_of(announcement_title: str) -> str:
    """ "... jednolitego tekstu ustawy o X" -> "Ustawa o X"; "... ustawy - Kodeks X" -> "Kodeks X"."""
    m = re.search(r"jednolitego tekstu ustawy\s*(.*)$", announcement_title)
    rest = (m.group(1) if m else announcement_title).strip().rstrip(".")
    if rest.startswith("-"):
        return rest.lstrip("- ").strip()
    return f"Ustawa {rest}".strip()


def sort_key(act_id: str) -> tuple[int, int]:
    _, year, pos = act_id.split("/")
    return int(year), int(pos)


def main() -> int:
    http = PoliteHttp(CACHE, USER_AGENT, allowed_hosts={"api.sejm.gov.pl"}, crawl_delay=5.0)
    http.get("https://api.sejm.gov.pl/robots.txt", cache_key="robots.txt")  # 404 = no restrictions
    announcements = all_announcements(http)
    by_act: dict[str, list[dict[str, Any]]] = {}
    for a in announcements:
        targets = [r["id"] for r in (a.get("references") or {}).get("Tekst jednolity dla aktu") or []]
        if len(targets) != 1 or not a.get("legalStatusDate"):
            continue  # a text that consolidates several acts, or without a legal-status date: not listed
        by_act.setdefault(targets[0], []).append(a)
    pilot_acts = {p["act"] for p in PILOT}
    entries: list[dict[str, Any]] = []
    n_current = n_nohtml = n_stale = 0
    for act_id in sorted(by_act, key=sort_key):
        texts = sorted(by_act[act_id], key=lambda a: (a["legalStatusDate"], sort_key(a["ELI"])))
        if not any(t["inForce"] == "IN_FORCE" for t in texts):
            continue
        n_current += 1
        html = [t for t in texts if t.get("textHTML") is True]
        if not html:
            n_nohtml += 1
            continue
        newest_html = html[-1]
        if (
            sort_key(texts[-1]["ELI"]) != sort_key(newest_html["ELI"])
            and texts[-1]["legalStatusDate"] > newest_html["legalStatusDate"]
        ):
            n_stale += 1
        if act_id in pilot_acts:
            continue
        entries.append(
            {
                "key": act_id.lower().replace("/", "-"),
                "title": title_of(newest_html["title"]),
                "act": act_id,
                "consolidated": [newest_html["ELI"]],
            }
        )
    listed_pilot = [p for p in PILOT if p["act"] in by_act]
    instruments = [*PILOT, *entries]
    n_listed = len(instruments)
    requests = sum(2 * len(i["consolidated"]) + 1 for i in instruments)
    header = HEADER.format(
        read_on=datetime.now(UTC).date().isoformat(),
        n_current=n_current,
        n_nohtml=n_nohtml,
        n_listed=n_listed,
        n_pilot=len(listed_pilot),
        n_new=len(entries),
        n_stale=n_stale,
        requests=requests,
        hours=requests * 5 / 3600,
    )
    manifest = {
        "schema_version": 1,
        "source_id": "pl-eli-sejm",
        "base_url": BASE,
        "user_agent": USER_AGENT,
        "crawl_delay_seconds": 5,
        # One act that is gone or whose page differs from its record is reported as a run error; the run goes on.
        "on_instrument_error": "skip",
        "instruments": instruments,
    }
    OUT.write_text(
        header + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=200),
        encoding="utf-8",
    )
    print(
        f"{len(announcements)} announcements, {len(by_act)} acts, {n_current} with a current text, "
        f"{n_nohtml} without HTML, {n_stale} with a newer PDF-only text, {n_listed} instruments, {requests} requests"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

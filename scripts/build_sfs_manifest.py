"""Write config/manifests/se-riksdagen-sfs.yaml from the Riksdag's own document list.

    python scripts/build_sfs_manifest.py

The Riksdag's open data lists every consolidated statute in Svensk författningssamling as a document of type
``sfs`` / subtype ``sfst`` (https://data.riksdagen.se/dokumentlista/?doktyp=sfs&utformat=json). The script pages
through that list (200 per page, about 90 requests, one per 5 s, cached under var/sources/) and writes one
``works`` entry per statute: its SFS number as the list prints it (``beteckning``, from which the Riksdag's document id
is formed) and its title. The eight statutes the pilot started with stay first. Repealed statutes are left out (the
list's status line says "Författningen är upphävd"), and so are records without an SFS number of the forms the parser
reads (``YYYY:N``, or with the balk or page suffix a few old statutes carry, ``1736:0123 2``, ``1904:48 s.1``): the N
series, RFS and supplement (``bih.``) references. A statute the list spells twice (``1904:48 s.1`` and ``1904:48s1``) is
listed once; a statute repealed after the list was made is skipped by the parser (record with ``upphavd``).
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

import yaml

from ulis.sources.connectors.polite_http import PoliteHttp
from ulis.sources.parsers.riksdagen_sfs import parse_sfs_number

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "se-riksdagen-sfs.yaml"
USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
HOST = "data.riksdagen.se"
LIST_URL = f"https://{HOST}/dokumentlista/?doktyp=sfs&utformat=json&sz=200&p={{page}}"
FIRST = ["1974:152", "1962:700", "1915:218", "1958:637", "1982:80", "2017:900", "2018:218", "1942:740"]
MAX_PAGES = 50  # 50 x 200 = the 10,000 hits the list serves per query
HEADER = """# Consolidated Swedish statutes (laws, ordinances, notices in Svensk författningssamling) fetched from the
# Riksdag's open data, one JSON document each, current consolidation only. Generated by
# scripts/build_sfs_manifest.py from the Riksdag's own document list
# (https://data.riksdagen.se/dokumentlista/?doktyp=sfs&utformat=json): {total} records on {built}, of which {count}
# are statutes in force with an SFS number (YYYY:N; {suffixed} of them with the balk or page suffix a few old statutes
# carry, e.g. 1736:0123 2, 1904:48 s.1); {repealed} repealed statutes ("Författningen är upphävd" in the list) and
# {other} N-series, RFS and supplement (bih.) records without such a number are left out.
# The eight statutes the pilot started with come first; the rest follow by SFS number.
# Terms: free use and redistribution with attribution "Källa: Sveriges riksdag" (användningsvillkor).
# `sfs` is the statute's number in Svensk författningssamling as the Riksdag's list prints it; the document is
# https://data.riksdagen.se/dokument/sfs-<number with ":" replaced by "-">.json (current consolidation only).
# Pace: one connection, 1 s between request starts (the project minimum). The publisher states no rate:
# https://data.riksdagen.se/robots.txt answers 404 (2026-10-18 10:58 UTC); https://www.riksdagen.se/robots.txt sets
# "crawl-delay:1" only for named crawlers (read strictly, 1 s is the only rate the Riksdag states, so it is the
# minimum); the open-data pages and terms give no limit (read 2026-10-18). A Crawl-delay in data.riksdagen.se's
# robots.txt would win.
# Scale: {count} documents at one request per 1 s is about {hours:.1f} hours of network time. A statute repealed after
# this list was made is fetched and skipped by the parser (record with "upphavd"). To ingest a part only, copy this
# file and delete works.
"""


def classify(doc: dict) -> tuple[str, str, str]:
    """One record of the list: ("work", number as printed, title), or ("repealed" | "other" | "foreign", id, "")."""
    doc_id = str(doc.get("id"))
    if doc.get("doktyp") != "sfs" or doc.get("subtyp") != "sfst":
        return "foreign", doc_id, ""  # the Riksbank's and the National Debt Office's regulations are in the list too
    if "upphävd" in str((doc.get("sokdata") or {}).get("statusrad") or ""):
        return "repealed", doc_id, ""  # "Författningen är upphävd": the statute is no longer in force
    number = " ".join(str(doc.get("beteckning", "")).split())
    if parse_sfs_number(number) is None:
        return "other", doc_id, ""  # N-series, RFS and supplement (bih.) references: no SFS number the parser reads
    return "work", number, re.sub(r"\s+", " ", doc.get("titel") or "").strip()


def read_list(
    http: PoliteHttp, order: str, seen: set[str], works: dict[str, tuple[str, str]], other: set[str], repealed: set[str]
) -> int:
    """Read pages of the list in one sort order until the window (10,000 hits) or the whole list is read."""
    page, pages, total = 1, 1, 0
    while page <= min(pages, MAX_PAGES):
        got = http.get(LIST_URL.format(page=page) + order)
        if got is None:
            raise SystemExit(f"page {page}: not found")
        listing = json.loads(got[0])["dokumentlista"]
        pages, total = int(listing["@sidor"]), int(listing["@traffar"])
        for doc in listing.get("dokument") or []:
            seen.add(str(doc.get("id")))
            kind, key, title = classify(doc)
            if kind == "work":
                number = parse_sfs_number(key)
                assert number is not None
                # One statute per number: when the list spells a number twice ("1904:48 s.1" and "1904:48s1"), the
                # canonical spelling is kept.
                if number.canonical not in works or (key == number.canonical and works[number.canonical][0] != key):
                    works[number.canonical] = (key, title)
            elif kind == "repealed":
                repealed.add(key)
            elif kind == "other":
                other.add(key)
        if len(seen) >= total:
            break
        page += 1
    return total


def main() -> int:
    http = PoliteHttp(ROOT / "var" / "sources", USER_AGENT, allowed_hosts={HOST}, crawl_delay=5.0)
    works: dict[str, tuple[str, str]] = {}  # canonical number -> (number as the list prints it, title)
    other: set[str] = set()
    repealed: set[str] = set()
    seen: set[str] = set()
    # The list serves at most 10,000 hits per query (page 51 of 200 is HTTP 400), so it is read in the default order
    # and then oldest first, newest first; together the windows must cover the whole list.
    total = 0
    for order in ("", "&sort=datum&sortorder=asc", "&sort=datum&sortorder=desc"):
        if total and len(seen) >= total:
            break
        total = read_list(http, order, seen, works, other, repealed)
    if len(seen) != total:
        raise SystemExit(f"the list reports {total} documents but {len(seen)} were read")
    print(f"{len(other)} records without an SFS number are not listed, e.g. {sorted(other)[:4]}")
    print(f"{len(repealed)} repealed statutes are not listed")

    def by_number(key: str) -> tuple[int, int, str, int]:
        number = parse_sfs_number(key)
        assert number is not None
        return number.year, int(number.serial), number.balk or "", int(number.page or 0)

    rest = sorted((k for k in works if k not in FIRST), key=by_number)
    ordered = [k for k in FIRST if k in works] + rest
    suffixed = [k for k in ordered if " " in k]
    print(f"{len(suffixed)} statutes with a balk or page suffix are listed: {suffixed}")
    head = {
        "schema_version": 1,
        "source_id": "se-riksdagen-sfs",
        "base_url": "https://data.riksdagen.se/dokument",
        "user_agent": USER_AGENT,
        "crawl_delay_seconds": 1,
    }
    header = HEADER.format(
        count=len(ordered),
        built=date.today().isoformat(),
        hours=len(ordered) * 1 / 3600,
        repealed=len(repealed),
        other=len(other),
        total=total,
        suffixed=len(suffixed),
    )
    lines = [f'  - {{sfs: "{works[k][0]}", title: {json.dumps(works[k][1], ensure_ascii=False)}}}' for k in ordered]
    body = yaml.safe_dump(head, sort_keys=False, allow_unicode=True) + "works:\n" + "\n".join(lines) + "\n"
    OUT.write_text(header + body, encoding="utf-8")
    print(f"{len(ordered)} statutes in the manifest ({http.requests_made} requests)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

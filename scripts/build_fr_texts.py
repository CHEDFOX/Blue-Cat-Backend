"""Builds ``ulis/sources/parsers/fr_texts_data.py`` from the titles of the texts the LEGI connector selected.

Usage (after an ingestion run of ``fr-dila-legi`` has filled the connector's work directory)::

    python scripts/build_fr_texts.py var/sources/echanges.dila.gouv.fr/legi-work/<stock date>/state.json

The tables map the French way of naming a text in a decision ("code civil", "loi n° 78-17") to the identifier of the
consolidated text in the DILA database (``LEGITEXT...`` for a code, ``JORFTEXT...`` for a law), using only the titles
the
DILA gives. A code whose name is shared by two texts (the "ancien" and the "nouveau" code) is left out: it cannot be
linked without guessing which one a decision means.
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "ulis" / "sources" / "parsers" / "fr_texts_data.py"
KINDS = {
    "LOI": "loi",
    "LOI_ORGANIQUE": "loi organique",
    "LOI_CONSTIT": "loi constitutionnelle",
    "ORDONNANCE": "ordonnance",
    "DECRET_LOI": "décret-loi",
}


def normal(name: str) -> str:
    return re.sub(r"\s+", " ", name.replace("’", "'").strip().lower())


def main(state_path: str) -> None:
    texts = json.loads(Path(state_path).read_text(encoding="utf-8"))["texts"]
    codes: dict[str, set[str]] = defaultdict(set)
    laws: dict[tuple[str, str], set[str]] = defaultdict(set)
    for tid, info in texts.items():
        title = info.get("title") or ""
        if info.get("nature") == "CODE":
            if info.get("tree") != "code_en_vigueur":
                continue
            codes[normal(re.sub(r"\s*\((?:nouveau|ancien)\)\s*$", "", title, flags=re.I))].add(tid)
        elif info.get("nature") in KINDS:
            match = re.search(r"\bn\s*°\s*(\d{2,4}-\d+)", title)
            if match:
                laws[(KINDS[info["nature"]], match.group(1))].add(tid)
    lines = [
        '"""Names of French texts -> identifiers in the DILA LEGI database (generated by scripts/build_fr_texts.py).',
        "",
        "Source: the titles of the codes in force (code_en_vigueur) and of the laws, organic laws,",
        "constitutional laws, ordinances and decree-laws of the LEGI stock",
        "Freemium_legi_global_20250713-140000.tar.gz. Do not edit by hand.",
        '"""',
        "",
        "# ruff: noqa: E501",
        "",
        "from __future__ import annotations",
        "",
        "CODES: dict[str, str] = {",
    ]
    for name in sorted(codes):
        if len(codes[name]) == 1:
            lines.append(f"    {name!r}: {next(iter(codes[name]))!r},")
    lines += ["}", "", "LAWS: dict[tuple[str, str], str] = {"]
    for key in sorted(laws):
        if len(laws[key]) == 1:
            lines.append(f"    {key!r}: {next(iter(laws[key]))!r},")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    skipped_codes = sorted(n for n, v in codes.items() if len(v) > 1)
    skipped_laws = sum(1 for v in laws.values() if len(v) > 1)
    kept = f"{len(codes) - len(skipped_codes)} codes, {len(laws) - skipped_laws} laws"
    print(f"{kept}; shared names left out: {skipped_codes}")


if __name__ == "__main__":
    main(sys.argv[1])

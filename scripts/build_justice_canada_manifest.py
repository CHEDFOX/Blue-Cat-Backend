"""Build config/manifests/ca-justice-laws-xml.yaml from a checkout of github.com/justicecanada/laws-lois-xml.

Each Act is pinned in both official languages (``eng/acts/<N>.xml`` and ``fra/lois/<N>.xml``)
and must parse; a file that does not is an error, not a silent omission.

    python scripts/build_justice_canada_manifest.py /path/to/laws-lois-xml A-1 P-21 ...
    python scripts/build_justice_canada_manifest.py /path/to/laws-lois-xml --all    # every Act in both languages

With ``--all`` an Act is included only if both language files exist and parse; the others are listed
in ``excluded`` in the manifest with the reason, so nothing is dropped silently.
"""

from __future__ import annotations

import hashlib
import subprocess  # noqa: S404
import sys
from pathlib import Path

import yaml

from ulis.sources.parsers.justice_canada import parse_justice_canada

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "ca-justice-laws-xml.yaml"
FOLDERS = {"eng": "eng/acts", "fra": "fra/lois"}


def main(checkout: str, numbers: list[str]) -> int:
    repo = Path(checkout).resolve()
    excluded: list[dict[str, str]] = []
    if numbers == ["--all"]:
        numbers = sorted(
            p.stem for p in (repo / "eng" / "acts").glob("*.xml") if (repo / "fra" / "lois" / p.name).exists()
        )
    commit = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        check=True,  # noqa: S603, S607
        capture_output=True,
        text=True,
    ).stdout.strip()
    documents = []
    for number in numbers:
        entries = []
        try:
            for lang, folder in FOLDERS.items():
                rel = f"{folder}/{number}.xml"
                content = (repo / rel).read_bytes()
                doc = parse_justice_canada(content)[0]
                entries.append(
                    {
                        "path": rel,
                        "external_id": f"justice-canada:{lang}:{number}",
                        "media_type": "application/xml",
                        "sha256": hashlib.sha256(content).hexdigest(),
                        "title": doc.title,
                        "point_in_time": doc.version_date.isoformat(),
                    }
                )
        except Exception as exc:  # noqa: BLE001 - recorded, not hidden
            if "--all" not in sys.argv:
                raise
            excluded.append({"act": number, "reason": f"{type(exc).__name__}: {str(exc)[:120]}"})
            continue
        documents.extend(entries)
    manifest = {
        "schema_version": 1,
        "source_id": "ca-justice-laws-xml",
        "repository": "https://github.com/justicecanada/laws-lois-xml",
        "commit": commit,
        "sparse": True,
        "documents": documents,
    }
    if excluded:
        manifest["excluded"] = excluded
    header = (
        "# Consolidated Acts of Canada (English and French), pinned to one commit.\n"
        "# Generated by scripts/build_justice_canada_manifest.py. Open Government Licence - Canada.\n"
    )
    OUT.write_text(header + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"{len(documents)} documents pinned at {commit}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2:]))

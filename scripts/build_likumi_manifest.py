"""Write config/manifests/lv-likumi.yaml: the laws and Cabinet regulations of Likumi.lv.

    python -m scripts.build_likumi_manifest

Likumi.lv has no machine-readable list of the acts in force: its listings (``/ta/veids/...``) are filled by a POST to
``/search.php``, which robots.txt disallows, and the portal publishes no open-data dump or API. What it does publish
is the sitemap named in its robots.txt (``Sitemap: https://likumi.lv/sitemap-index.xml``: three files, about 125 000
addresses, 30 MB, 4 requests in all). A sitemap entry says nothing about the type or the status of a document, only
its address ``/ta/id/<id>-<slug>`` (the slug is the document's title in ASCII), so the manifest lists *candidates* and
the parser decides: a page that is not a law (Veids "likums") or a Cabinet regulation (Veids "noteikumi", issuer
"Ministru kabinets"), or whose status is not "Spēkā esošs", is skipped (``ParseSkipped``), not an error.

Candidate rules (applied to the sitemap, nothing else is fetched):

* only Latvian-original addresses ``/ta/id/<id>-<slug>``; the ``/ta/<lang>/starptautiskie-ligumi/`` addresses
  (treaties and their translations) are not candidates;
* not amending acts (slug starts ``grozijum``: "Grozījumi ... likumā / noteikumos"; their changes are in the
  consolidated text of the act they amend), not orders ("Par ..." - rīkojumi, mostly appointments and travel), not
  municipal binding rules (``saistosie``), local plans (``lokalplanojum``), notices (``pazinojums``) or Cabinet minutes;
* not the ids that robots.txt names (``Disallow: /*id=<id>`` rules, a few hundred);
* the ten pilot documents first, then the curated "Par ..." laws below, then every other candidate by id.

Known limit: laws whose title begins "Par ..." (about a dozen in force) and Cabinet regulations whose title begins
"Par ..." are not candidates except the curated ones; every other law and regulation is, whatever its title.
"""

from __future__ import annotations

import re
import sys
from datetime import UTC, datetime
from pathlib import Path

import yaml

from ulis.sources.connectors.likumi_lv import disallowed_ids
from ulis.sources.connectors.polite_http import PoliteHttp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "lv-likumi.yaml"
CACHE = ROOT / "var" / "sources"
HOST = "likumi.lv"
USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
PILOT = [
    {"id": 57980, "title": "Latvijas Republikas Satversme"},  # constitution
    {"id": 88966, "title": "Krimināllikums"},  # criminal law
    {"id": 90224, "title": "Civillikums. Ievads"},  # civil law
    {"id": 90223, "title": "Civillikums. PIRMĀ DAĻA. Ģimenes tiesības"},
    {"id": 90222, "title": "Civillikums. OTRĀ DAĻA. Mantojuma tiesības"},
    {"id": 90221, "title": "Civillikums. TREŠĀ DAĻA. Lietu tiesības"},
    {"id": 90220, "title": "Civillikums. CETURTĀ DAĻA. Saistību tiesības"},
    {"id": 300099, "title": "Fizisko personu datu apstrādes likums"},  # data processing
    {"id": 26019, "title": "Darba likums"},  # labour law
    {"id": 55567, "title": "Administratīvā procesa likums"},  # administrative procedure
]
# Laws titled "Par ..." (the slug starts "par-", like the orders); the parser checks type and status.
CURATED_PAR_SLUGS = {
    "par-nodokliem-un-nodevam",
    "par-iedzivotaju-ienakuma-nodokli",
    "par-valsts-pensijam",
    "par-nekustama-ipasuma-nodokli",
    "par-budzetu-un-finansu-vadibu",
}
EXCLUDED_PREFIXES = (
    "grozijum",  # grozījumi / grozījums: amending acts
    "par-",  # orders (rīkojumi)
    "saistosie",  # municipal binding rules
    "pazinojums",  # notices
    "lokalplanojum",  # local plans
    "ministru-kabineta-sedes",  # Cabinet minutes
    "ministru-kabineta-attalinata",
)
HEADER = """\
# Latvian laws and Cabinet regulations fetched from Likumi.lv (official publisher "Latvijas Vēstnesis"): one page per
# document, the current ("spēkā esošā") edition. Generated by `python -m scripts.build_likumi_manifest` from the
# portal's sitemap (https://likumi.lv/sitemap-index.xml, named in robots.txt; read {read_on}); see the script for the
# rules. Copyright Law (Autortiesību likums) Art. 6(1): legislative acts and their official consolidated versions are
# not protected by copyright; the portal's terms (https://likumi.lv/par-mums/portala-lietosanas-noteikumi) grant free
# access and forbid no copying. `id` is the document's number on the site (https://likumi.lv/ta/id/<id>, the address
# the page itself gives as its own). The Civillikums is published in five parts, each with its own edition history, so
# each part is ingested as its own document (the combined page /ta/id/225418 is not used). Earlier editions
# (/redakcijas-datums/...) are disallowed by robots.txt and are never requested.
#
# SCALE. The sitemap lists {n_sitemap} addresses; {n_candidates} are candidates (the ten pilot documents, {n_par}
# curated "Par ..." laws, {n_rest} others). The sitemap does not say what a page is, so the parser skips what is not a
# law or a Cabinet regulation in force. A random sample of 160 candidates (seed 20261015, fetched 2026-10-15) gave: 32
# ingested (27 Cabinet regulations and 5 laws), 53 laws or regulations no longer in force, 75 other documents
# (municipal binding rules, minutes, notices, heritage administrative acts, regulators' rules), 0 parse failures. So
# roughly one candidate in five is ingested: about 4 000 documents, about 90 provisions each (about 360 000
# provisions, some 1 GB of database). One request per candidate at 5 s: {requests} requests = {hours:.0f} hours, plus
# 5 for robots.txt and the sitemaps, and about 190 KB per page (about 4 GB). The default is the whole list; to ingest
# a part, give `ingest_in_batches.py --manifest` a shorter file (the ids are sorted). Not candidates: amending acts
# ("Grozījumi ..."), orders ("Par ..."), municipal binding rules, treaties and the English/Russian translations;
# documents of other types or issuers are skipped by the parser.
#
"""


def main() -> int:
    http = PoliteHttp(CACHE, USER_AGENT, allowed_hosts={HOST}, crawl_delay=5.0)
    robots = http.get(f"https://{HOST}/robots.txt")
    if robots is None:
        raise SystemExit("robots.txt not found; refusing to go on without reading it")
    blocked = disallowed_ids(robots[0].decode("utf-8", "replace"))
    index = http.get(f"https://{HOST}/sitemap-index.xml")
    assert index is not None
    sitemaps = re.findall(r"<loc>([^<]+)</loc>", index[0].decode("utf-8"))
    rows: dict[int, str] = {}
    n_addresses = 0
    for url in sitemaps:
        got = http.get(url)
        assert got is not None
        for m in re.finditer(r"<loc>https://likumi\.lv/ta/id/(\d+)-([^<]*)</loc>", got[0].decode("utf-8")):
            n_addresses += 1
            rows.setdefault(int(m.group(1)), m.group(2))
    pilot_ids = {p["id"] for p in PILOT}
    par = sorted(i for i, s in rows.items() if s in CURATED_PAR_SLUGS and i not in blocked)
    rest = sorted(
        i
        for i, s in rows.items()
        if i not in pilot_ids and i not in blocked and not s.startswith(EXCLUDED_PREFIXES) and i not in par
    )
    laws: list[dict[str, object]] = [*PILOT, *({"id": i} for i in par), *({"id": i} for i in rest)]
    requests = len(laws)
    header = HEADER.format(
        read_on=datetime.now(UTC).date().isoformat(),
        n_sitemap=f"{n_addresses:,}".replace(",", " "),
        n_candidates=f"{len(laws):,}".replace(",", " "),
        n_par=len(par),
        n_rest=f"{len(rest):,}".replace(",", " "),
        requests=f"{requests:,}".replace(",", " "),
        hours=requests * 5 / 3600,
    )
    manifest = {
        "schema_version": 1,
        "source_id": "lv-likumi",
        "base_url": f"https://{HOST}",
        "user_agent": USER_AGENT,
        "crawl_delay_seconds": 5,
        # A page that is gone, not a document page, or disallowed by a robots.txt that changed is reported as a run
        # error and the run goes on; a refusal (401/403/429/451) always stops it.
        "on_document_error": "skip",
        "laws": laws,
    }
    dumped = yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=200, default_flow_style=None)
    OUT.write_text(header + dumped, encoding="utf-8")
    print(f"{n_addresses} sitemap addresses, {len(blocked)} blocked ids, {len(laws)} candidates, {requests} requests")
    return 0


if __name__ == "__main__":
    sys.exit(main())

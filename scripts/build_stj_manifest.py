"""Write config/manifests/br-stj-dados-abertos.yaml from the STJ open data portal's dataset page.

    python scripts/build_stj_manifest.py                # use the cached dataset page, fetch it once if absent
    python scripts/build_stj_manifest.py --refresh      # fetch the dataset page again (one request, 4 MB)
    python scripts/build_stj_manifest.py --out /tmp/m.yaml --from 20260901 --to 20260930   # a slice, for trials

The dataset page (HTML, allowed by robots.txt; the CKAN API is not) lists every daily/monthly ZIP of texts and JSON of
metadata with its resource id; the manifest records them as ``<resource id>/<download name>`` so the connector can
build the download links. ``--from``/``--to`` keep only periods in that range (YYYYMMDD, compared as text). Run it
again to add the days published since; existing entries are rewritten identically.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

from ulis.settings import REPO_ROOT
from ulis.sources.connectors.moj_laws import robots_allows
from ulis.sources.connectors.polite_http import PoliteHttp
from ulis.sources.connectors.stj_dados_abertos import (
    DATASET_PAGE,
    HOST,
    MIN_DELAY,
    ROBOTS_URL,
    build_file_set,
    parse_resources,
    robots_crawl_delay,
)

USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
CACHE = REPO_ROOT / "var" / "sources"
OUT = REPO_ROOT / "config" / "manifests" / "br-stj-dados-abertos.yaml"
DATASET_ID = "a2cd85cc-1391-4ebc-aeed-a45dd75a7987"
HEADER = """# Superior Tribunal de Justica (Brazil): the daily/monthly files of the open data portal's dataset
# "Integras de Decisoes Terminativas e Acordaos do Diario da Justica"
# (https://dadosabertos.web.stj.jus.br/dataset/integras-de-decisoes-terminativas-e-acordaos-do-diario-da-justica,
# licence shown there: "Creative Commons Atribuicao"). One ZIP of texts and one JSON of metadata per period, from
# the first file (2021-01-04); `id` is the period (YYYYMMDD, or YYYYMM for the months the portal published as one
# file; a `-b` suffix marks a second upload of the same period); `zip`/`json` are "<resource id>/<download name>"
# and give the link <base_url>/dataset/<dataset_id>/resource/<resource id>/download/<download name>.
# `without_texts` lists periods the portal published metadata for but no ZIP (not fetched). Generated by
# scripts/build_stj_manifest.py from the dataset page; nothing here is fetched until the connector runs, at 10 s
# between requests (robots.txt Crawl-Delay).
"""


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--from", dest="start", default="")
    parser.add_argument("--to", dest="end", default="99999999")
    args = parser.parse_args(argv)

    http = PoliteHttp(CACHE, USER_AGENT, allowed_hosts={HOST}, crawl_delay=MIN_DELAY)
    got = http.get(ROBOTS_URL, cache_key="robots.txt")
    robots = got[0].decode("utf-8", "replace") if got else None
    if robots is not None:
        http.crawl_delay = max(http.crawl_delay, robots_crawl_delay(robots, USER_AGENT) or 0)
        if not robots_allows(robots, USER_AGENT, DATASET_PAGE):
            print(f"{DATASET_PAGE} is disallowed by robots.txt", file=sys.stderr)
            return 1
    key = "dataset_integras.html"
    if args.refresh:
        (http.cache_path(DATASET_PAGE, key)).unlink(missing_ok=True)
        http.cache_path(DATASET_PAGE, key).with_name(key + ".meta.json").unlink(missing_ok=True)
    page = http.get(DATASET_PAGE, cache_key=key)
    if page is None:
        print("dataset page not found", file=sys.stderr)
        return 1
    read_on = datetime.fromisoformat(page[1]["retrieved_at"]).astimezone(UTC).date().isoformat()
    resources = parse_resources(page[0].decode("utf-8", "replace"))
    files, without_texts = build_file_set(resources)
    files = [f for f in files if args.start <= str(f["id"])[:8].ljust(8, "0") <= args.end]
    without_texts = [p for p in without_texts if args.start <= p.ljust(8, "0") <= args.end]
    lines = [
        HEADER.rstrip("\n"),
        "schema_version: 1",
        "source_id: br-stj-dados-abertos",
        "base_url: https://dadosabertos.web.stj.jus.br",
        f'user_agent: "{USER_AGENT}"',
        f"crawl_delay_seconds: {int(MIN_DELAY)}",
        f"dataset_id: {DATASET_ID}",
        f'dataset_page_read_on: "{read_on}"',
        "without_texts: [" + ", ".join(f'"{p}"' for p in without_texts) + "]",
        "files:",
    ]
    for f in files:
        zip_ref, json_ref = f["zip"], f["json"]
        json_part = f', json: "{json_ref}"' if json_ref else ""
        lines.append(f'  - {{id: "{f["id"]}", zip: "{zip_ref}"{json_part}}}')
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    days = sum(1 for f in files if re.fullmatch(r"[0-9]{8}(-[b-z])?", str(f["id"])))
    print(f"{len(files)} entries ({days} daily, {len(files) - days} monthly), {len(without_texts)} without texts")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

"""Write config/manifests/ie-irish-statute-book.yaml from the electronic Irish Statute Book's own year lists.

    python scripts/build_ie_manifest.py [--from-year 1922] [--to-year 2026]

For every year of the Oireachtas the eISB serves a list of that year's Acts (``/eli/<year>/act/``) with the "Public
Acts" table: number and title of each Public General Act. The script reads those pages (one request per year, 5 s
apart, cached under var/sources/) and writes one ``acts`` entry per Public Act: year, number, title. The six Acts the
pilot started with keep their SHA-256 pins and stay first. Constitutional Amendment Acts and Private Acts are not
listed; the text is the Act AS ENACTED (later amendments and repeals are not applied).
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from datetime import date
from pathlib import Path

from ulis.sources.connectors.polite_http import PoliteHttp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "ie-irish-statute-book.yaml"
USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
HOST = "www.irishstatutebook.ie"
_ROW = re.compile(
    r'<tr>\s*<td class="align-center">(\d+)</td>\s*<td>\s*<a href="en/act/pub/(\d{4})/index\.html">([^<]+)</a>', re.S
)
# The six pilot Acts: pinned by the SHA-256 of the file downloaded on 2026-10-14.
PILOT = [
    (1977, 10, "Unfair Dismissals Act 1977", "8e57d6c911641590aa906b11dea65b71968cfb0cdc53fcada37f8e53399c1b6e"),
    (
        1997,
        26,
        "Non-Fatal Offences against the Person Act 1997",
        "6a190adca159146a09849f1b47d4f202f730e8c734eba4c3350304d1cbf6bb9b",
    ),
    (
        2001,
        50,
        "Criminal Justice (Theft and Fraud Offences) Act 2001",
        "c04b4aa830aadb7fdc83e3b1bda3b62a35bb70093b2623bbb4fb3acc87f18cdf",
    ),
    (2007, 19, "Consumer Protection Act 2007", "ee5685db428fa89ea3edfb1c7f4fa717006ed60f9e26c1adb3e79894d543d15c"),
    (2014, 38, "Companies Act 2014", "d241729149d3016591bea0dc4a1fc484a97c5704cf7dce56de494d2cb8c442a7"),
    (2018, 7, "Data Protection Act 2018", "5dff92237fc8144e9675ecd6c465b1bff973f2f4c88e003b6dab09c16294e9ec"),
]
HEADER = """# Public Acts of the Oireachtas AS ENACTED, fetched from the electronic Irish Statute Book (eISB), one XML
# file per Act:
#   https://www.irishstatutebook.ie/eli/<year>/act/<number>/enacted/en/xml
# (documented on https://www.irishstatutebook.ie/open-data.html). Re-use under the Oireachtas (Open Data) PSI
# Licence (CC BY 4.0).
# AS ENACTED: this is the text of each Act when it was passed. Amendments, repeals and commencement orders made since
# are NOT applied, so an Act listed here may have been amended heavily or repealed altogether; do not read it as the law
# in force today. The optional `sha256` pins the exact download (as retrieved on 2026-10-14).
# Generated by scripts/build_ie_manifest.py from the eISB's own list of each year's Public Acts
# (https://www.irishstatutebook.ie/eli/<year>/act/), {years}: {count} Public Acts listed on {built}.
# Scale: {count} documents at one request per 5 s is about {hours:.1f} hours of network time.
# Not listed: Constitutional Amendment Acts and Private Acts (different lists); Bunreacht na hÉireann (the Constitution)
# - eISB offers it as HTML/PDF only; /eli/cons/en/xml is 404.
"""


def titles(page: str) -> list[tuple[int, str]]:
    """(number, title) of each Public Act in a year's list; the link's own number must agree with the first column."""
    out: list[tuple[int, str]] = []
    for number, link_number, title in _ROW.findall(page):
        if int(number) != int(link_number):
            raise SystemExit(f"row {number} links to Act {link_number}")
        out.append((int(number), re.sub(r"\s+", " ", html.unescape(title)).strip()))
    return out


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--from-year", type=int, default=1922)
    parser.add_argument("--to-year", type=int, default=date.today().year)
    args = parser.parse_args(argv)
    http = PoliteHttp(ROOT / "var" / "sources", USER_AGENT, allowed_hosts={HOST}, crawl_delay=5.0)
    acts: list[tuple[int, int, str]] = []
    empty: list[int] = []
    for year in range(args.from_year, args.to_year + 1):
        got = http.get(f"https://{HOST}/eli/{year}/act/", cache_key=f"eli-lists/{year}.html")
        if got is None:
            empty.append(year)
            continue
        found = titles(got[0].decode("utf-8", "replace"))
        if not found:
            empty.append(year)
        acts.extend((year, number, title) for number, title in found)
    pinned = {(y, n) for y, n, _, _ in PILOT}
    rest = sorted((y, n, t) for y, n, t in acts if (y, n) not in pinned)
    missing = pinned - {(y, n) for y, n, _ in acts}
    if missing:
        raise SystemExit(f"pilot Acts missing from the lists: {sorted(missing)}")
    head = HEADER.format(
        years=f"{args.from_year}-{args.to_year}",
        count=len(acts),
        built=date.today().isoformat(),
        hours=len(acts) * 5 / 3600,
    )
    lines = [
        "schema_version: 1",
        "source_id: ie-irish-statute-book",
        "base_url: https://www.irishstatutebook.ie",
        f'user_agent: "{USER_AGENT}"',
        "crawl_delay_seconds: 5",
        "acts:",
    ]
    for y, n, t, sha in PILOT:
        lines.append(f"  - {{year: {y}, number: {n}, title: {json.dumps(t)}, sha256: {sha}}}")
    for y, n, t in rest:
        lines.append(f"  - {{year: {y}, number: {n}, title: {json.dumps(t, ensure_ascii=False)}}}")
    OUT.write_text(head + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(acts)} Public Acts in the manifest; years without a list: {empty}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

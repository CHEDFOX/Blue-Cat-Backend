"""Build the manifest of the Acts of Bhutan listed on the Judiciary of Bhutan's "Acts" page.

python scripts/build_bt_acts_manifest.py [--write] [--prune]

The page https://www.judiciary.gov.bt/posts/first-category/acts lists the Acts as paragraphs "Title (English)" with a link to a
PDF. The script reads that one page (robots.txt first, identifying User-Agent, cached under var/sources) and prints, or with
``--write`` writes, ``config/manifests/bt-judiciary-acts.yaml``: one document per English PDF, the Act's title as the page prints it.
With ``--prune`` the links that answered HTTP 404 in an earlier connector run (cached under var/sources) are left out.
"""

# ruff: noqa: E501
from __future__ import annotations

import html
import json
import re
import sys
import urllib.parse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ulis.sources.connectors.moj_laws import robots_allows  # noqa: E402
from ulis.sources.connectors.polite_http import PoliteHttp  # noqa: E402

UA = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
HOST = "www.judiciary.gov.bt"
PAGE = f"https://{HOST}/posts/first-category/acts"


# files that answered but that pdftotext cannot read (found by the run of 2026-10-16)
UNREADABLE = {"bt-bhutan-education-city-act-2012"}


def answered_404(slug: str) -> bool:
    """True when an earlier run of the connector cached an HTTP 404 for this document (var/sources)."""
    meta = ROOT / "var" / "sources" / HOST / "constitutions" / f"{slug}.pdf.meta.json"
    try:
        return bool(meta.exists() and json.loads(meta.read_text(encoding="utf-8")).get("status") == 404)
    except ValueError:
        return False


def slugify(text: str) -> str:
    ascii_text = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return ascii_text[:80].rstrip("-")


def main() -> int:
    http = PoliteHttp(ROOT / "var" / "sources", UA, allowed_hosts={HOST}, crawl_delay=5.0)
    robots = http.get(f"https://{HOST}/robots.txt", cache_key="robots.txt")
    if robots is not None and not robots_allows(robots[0].decode("utf-8", "replace"), UA, PAGE):
        print("the page is disallowed by robots.txt")
        return 1
    got = http.get(PAGE, cache_key="acts-page.html")
    if got is None:
        print("page not found")
        return 1
    page = got[0].decode("utf-8", errors="replace")
    prune = "--prune" in sys.argv
    dropped = 0
    documents: list[dict[str, object]] = []
    seen_urls: set[str] = set()
    seen_slugs: set[str] = set()
    for paragraph in re.findall(r"(?is)<p\b[^>]*>(.*?)</p>", page):
        links = re.findall(r'(?is)<a\b[^>]*href="([^"]+\.pdf)"[^>]*>(.*?)</a>', paragraph)
        if not links:
            continue
        title = re.sub(
            r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", re.sub(r"(?is)<a\b.*?</a>", " ", paragraph)))
        ).strip(" ()-\xa0")
        title = re.sub(r"\s*\(\s*(and\s*)?$", "", title).strip()
        for href, label in links:
            text = re.sub(r"<[^>]+>", "", html.unescape(label)).strip()
            if "english" not in text.lower() or not title:
                continue
            url = urllib.parse.urljoin(PAGE, href.replace("&amp;", "&"))
            url = urllib.parse.quote(url, safe=":/?&=%#@+,;~!$()*'[]")
            parts = urllib.parse.urlsplit(url)
            if parts.scheme not in ("http", "https") or parts.netloc != HOST or url in seen_urls:
                continue
            url = "https://" + parts.netloc + parts.path + (f"?{parts.query}" if parts.query else "")
            slug = f"bt-{slugify(title)}"
            n = 2
            while slug in seen_slugs:
                slug = f"bt-{slugify(title)}-{n}"
                n += 1
            seen_urls.add(url)
            seen_slugs.add(slug)
            if slug in UNREADABLE or (prune and answered_404(slug)):
                dropped += 1
                continue
            documents.append(
                {
                    "slug": slug,
                    "jurisdiction": "BT",
                    "url": url,
                    "format": "pdf",
                    "language": "en",
                    "instrument_type": "act",
                    "title": title,
                    "citation_name": title,
                    "authoritative": False,
                    "text_origin": "official_consolidation",
                    "structure": {"page_numbers": True},
                }
            )
    header = (
        "# Acts of Bhutan in English, as listed on the Judiciary of Bhutan's page "
        f"{PAGE} - generated by scripts/build_bt_acts_manifest.py.\n"
        f"# {len(documents)} documents ({dropped} links of the page left out: they answered HTTP 404 or are not readable on "
        f"2026-10-16; run with --prune after a connector run to refresh); one request each at the 5 s crawl delay (about {len(documents) * 5 / 60:.0f} minutes "
        "of waiting), plus robots.txt. A link that no longer answers is skipped and reported as a run error.\n"
    )
    manifest = {
        "schema_version": 1,
        "source_id": "bt-judiciary-acts",
        "user_agent": UA,
        "crawl_delay_seconds": 5,
        "hosts": [HOST],
        "documents": documents,
    }
    text = header + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=140)
    if "--write" in sys.argv:
        (ROOT / "config" / "manifests" / "bt-judiciary-acts.yaml").write_text(text, encoding="utf-8")
        print(f"wrote {len(documents)} documents")
    else:
        print(text[:3000])
        print(len(documents), "documents")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Build config/manifests/us-gpo-uslm-samples.yaml from a checkout of github.com/usgpo/uslm.

Every candidate file is parsed; files the parser cannot handle are listed under `excluded`
with the reason, so nothing is dropped silently.

    python scripts/build_uslm_manifest.py /path/to/uslm-checkout
"""

from __future__ import annotations

import hashlib
import subprocess  # noqa: S404
import sys
from pathlib import Path

import yaml

from ulis.sources.parsers.uslm import UslmParseError, parse_uslm

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "us-gpo-uslm-samples.yaml"
PATTERNS = [
    "previous/sample-files/*publ*-uslm.xml",
    "previous/sample-files/COMPS-*.xml",
    "previous/sample-files/CFR-*-uslm.xml",
    "bill-version-samples-september-2024/*.[xX][mM][lL]",
]


def main(checkout: str) -> int:
    repo = Path(checkout).resolve()
    commit = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        check=True,  # noqa: S603, S607
        capture_output=True,
        text=True,
    ).stdout.strip()
    documents, excluded = [], []
    for pattern in PATTERNS:
        for path in sorted(repo.glob(pattern)):
            rel = path.relative_to(repo).as_posix()
            content = path.read_bytes()
            try:
                docs = parse_uslm(content)
            except UslmParseError as exc:
                excluded.append({"path": rel, "reason": str(exc)})
                continue
            documents.append(
                {
                    "path": rel,
                    "external_id": "usgpo-uslm:" + path.stem.lower(),
                    "media_type": "application/xml",
                    "sha256": hashlib.sha256(content).hexdigest(),
                    "kinds": sorted({d.instrument_type for d in docs}),
                }
            )
    manifest = {
        "schema_version": 1,
        "source_id": "us-gpo-uslm-samples",
        "repository": "https://github.com/usgpo/uslm",
        "commit": commit,
        "documents": documents,
        "excluded": excluded,
    }
    header = (
        "# US GPO USLM sample files, pinned to one commit. Generated by scripts/build_uslm_manifest.py.\n"
        "# Public domain (17 U.S.C. 105) with a CC0 waiver - see the repository LICENSE.md.\n"
    )
    OUT.write_text(header + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"{len(documents)} documents, {len(excluded)} excluded, commit {commit}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))

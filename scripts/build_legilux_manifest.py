"""Build config/manifests/lu-legilux.yaml from the Legilux linked-data (SPARQL) endpoint.

It lists every consolidation (``jolux:Consolidation``) of Luxembourg legislation under
``/eli/etat/leg/`` that has an Akoma Ntoso XML file in French, grouped by consolidated work (a code, the
Constitution, a consolidated law or regulation) with the dates of applicability, oldest first:

* ``recueil/*`` (non-authoritative thematic compilations that repeat the text of other acts) and
  administrative acts under ``/eli/etat/adm/`` (disallowed by the robots.txt of legilux.public.lu) are left out;
* consolidations applicable after the build date (published in advance) are recorded under ``scheduled``
  and not fetched;
* consolidations without an XML file (some codes only exist as HTML, PDF and Word files) are counted, not listed.

The file URL of each consolidation is derived from its ELI (see ``connectors/legilux.file_url``); the script
checks the derivation against the file location the linked data states and stops if they differ.

Requests go through PoliteHttp (identifying User-Agent, 5 s between requests, cached); one SPARQL query.

    python scripts/build_legilux_manifest.py [YYYY-MM-DD]
"""

from __future__ import annotations

import collections
import json
import sys
import urllib.parse
from datetime import date
from pathlib import Path

import yaml

from ulis.sources.connectors.legilux import ELI_PREFIX, SPARQL_ENDPOINT, USER_AGENT, file_url
from ulis.sources.connectors.polite_http import PoliteHttp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "lu-legilux.yaml"
DATA_FILESTORE = "http://data.legilux.public.lu/"

QUERY = """PREFIX jolux: <http://data.legilux.public.lu/resource/ontology/jolux#>
SELECT ?c ?x WHERE {
  ?c a jolux:Consolidation .
  FILTER(STRSTARTS(STR(?c), "%s"))
  OPTIONAL {
    ?c jolux:isRealizedBy ?e . ?e jolux:isEmbodiedBy ?m .
    FILTER(STRENDS(STR(?m), "/fr/xml"))
    ?m jolux:isExemplifiedBy ?x
  }
} ORDER BY ?c
""" % ELI_PREFIX

HEADER = """# Luxembourg consolidated legislation from Legilux (Akoma Ntoso XML, French).
# Generated by scripts/build_legilux_manifest.py from the Legilux SPARQL endpoint
# (https://data.legilux.public.lu/sparqlendpoint). Files are listed in the linked data under
# data.legilux.public.lu/filestore/ (whose robots.txt disallows that path) and fetched from the public
# filestore of the Legilux website, legilux.public.lu/filestore/ (see config/sources/lu-legilux.yaml).
# Consolidated texts have no legal value: the authentic text is the one published in the Mémorial A.
# Licence: CC BY 4.0, attribution to the Ministère d'Etat - Service central de législation.
"""


def main() -> None:
    built_on = date.fromisoformat(sys.argv[1]) if len(sys.argv) > 1 else date.today()
    http = PoliteHttp(
        ROOT / "var" / "sources",
        USER_AGENT,
        allowed_hosts={"data.legilux.public.lu"},
        crawl_delay=5.0,
        timeout=300,
    )
    url = SPARQL_ENDPOINT + "?" + urllib.parse.urlencode({"query": QUERY})
    got = http.get(url, cache_key=f"sparql-consolidations-{built_on.isoformat()}.json", headers={"Accept": "application/json"})
    if got is None:
        raise SystemExit("SPARQL endpoint answered 404")
    rows = json.loads(got[0])["results"]["bindings"]

    works: dict[str, list[date]] = collections.defaultdict(list)
    scheduled: dict[str, list[date]] = collections.defaultdict(list)
    skipped = collections.Counter()
    for row in rows:
        eli = row["c"]["value"]
        path, _, stamp = eli.removeprefix(ELI_PREFIX).rpartition("/")
        if len(stamp) != 8 or not stamp.isdigit() or not path:
            skipped["unexpected consolidation URI"] += 1
            continue
        if path.startswith("recueil/"):
            skipped["recueil (thematic compilation)"] += 1
            continue
        if "x" not in row:
            skipped["no XML file"] += 1
            continue
        day = date(int(stamp[:4]), int(stamp[4:6]), int(stamp[6:]))
        expected = file_url(path, day).replace("https://legilux.public.lu/", DATA_FILESTORE)
        if row["x"]["value"] != expected:
            raise SystemExit(f"file location differs from the derived URL:\n  {row['x']['value']}\n  {expected}")
        (scheduled if day > built_on else works)[path].append(day)

    manifest = {
        "schema_version": 1,
        "source_id": "lu-legilux",
        "built_on": built_on.isoformat(),
        "sparql_endpoint": SPARQL_ENDPOINT,
        "user_agent": USER_AGENT,
        "crawl_delay_seconds": 5,
        "languages": ["fr"],
        "works": [
            {
                "path": path,
                "consolidations": [d.isoformat() for d in sorted(set(days))],
                **({"scheduled": [d.isoformat() for d in sorted(scheduled[path])]} if scheduled.get(path) else {}),
            }
            for path, days in sorted(works.items())
        ],
    }
    OUT.write_text(HEADER + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True), encoding="utf-8")
    total = sum(len(w["consolidations"]) for w in manifest["works"])
    kinds = collections.Counter(w["path"].split("/")[0] for w in manifest["works"])
    print(f"{OUT}: {len(manifest['works'])} works, {total} consolidations; by kind {dict(kinds)}")
    print(f"scheduled (after {built_on}, not fetched): {sum(len(v) for v in scheduled.values())}; skipped: {dict(skipped)}")


if __name__ == "__main__":
    main()

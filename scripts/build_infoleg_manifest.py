"""Write config/manifests/ar-infoleg.yaml: every national law (``tipo_norma`` "Ley") whose text InfoLEG publishes.

    python -m scripts.build_infoleg_manifest

The list comes from the Ministry of Justice's open-data record "Base Infoleg de Normativa Nacional"
(https://datos.gob.ar/dataset/justicia-base-infoleg-normativa-nacional, CC BY 4.0): one zip of one CSV
(base-infoleg-normativa-nacional.zip, ~50 MB, a single request to datos.jus.gob.ar; robots.txt of both hosts allows
dataset downloads and sets Crawl-delay 10). The CSV has one row per norm with its metadata and, where InfoLEG has the
text, a link to the original text (``texto_original``) and/or the updated text (``texto_actualizado``). A law is listed
when it has at least one of them; the updated text is preferred ("actualizado where it exists"). The CSV links point to
the legacy host (servicios.infoleg.gob.ar), which ULIS does not use: the connector reads the same texts from
www.argentina.gob.ar/normativa/nacional/norma-<id>/(actualizacion|texto), the pages behind the site's own buttons.

The six instruments of the pilot keep their entries unchanged (they are read from the summary page too). Every other
entry carries ``dataset_row``: the CSV row's metadata, so that the connector needs one request per law (the text page)
instead of two. Not listed: the 19,500 laws the CSV marks with no text at all (InfoLEG has only a summary of them) and
the two laws without a number ("S/N", 1853 and 1862). Where one law number was issued twice (13 numbers before 1863),
``number_ambiguous`` makes the parser add the year of sanction to the work URI.
"""

# ruff: noqa: E501 - the generated manifest header and the pilot entries are written as long lines

from __future__ import annotations

import csv
import hashlib
import io
import json
import re
import sys
import zipfile
from collections import Counter
from typing import Any

import yaml

from ulis.settings import REPO_ROOT
from ulis.sources.connectors.polite_http import PoliteHttp

OUT = REPO_ROOT / "config" / "manifests" / "ar-infoleg.yaml"
CACHE = REPO_ROOT / "var" / "sources"
USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
DATASET_PAGE = "https://datos.gob.ar/dataset/justicia-base-infoleg-normativa-nacional"
ZIP_URL = (
    "https://datos.jus.gob.ar/dataset/d9a963ea-8b1d-4ca3-9dd9-07a4773e8c23/resource/"
    "bf0ec116-ad4e-4572-a476-e57167a84403/download/base-infoleg-normativa-nacional.zip"
)
ZIP_KEY = "infoleg-dataset/base-infoleg-normativa-nacional.zip"
CRAWL_DELAY = 10
KEEP = (
    "tipo_norma",
    "numero_norma",
    "organismo_origen",
    "fecha_sancion",
    "numero_boletin",
    "fecha_boletin",
    "pagina_boletin",
    "titulo_resumido",
    "titulo_sumario",
    "observaciones",
    "modificada_por",
    "modifica_a",
)
HEADER = """# Argentine national LAWS (tipo_norma "Ley") from InfoLEG (Ministerio de Justicia,
# https://www.argentina.gob.ar/normativa). Per law, the text page /normativa/nacional/norma-<id>/(actualizacion|texto)
# ("texto actualizado" where InfoLEG has one, else the "texto original"). `id` is InfoLEG's norm id. Entries with
# `dataset_row` take their metadata from the open-data CSV (one request per law); the first six (the pilot) are read
# from the summary page as before (two requests per law).
# Terms: https://www.argentina.gob.ar/terminos-y-condiciones (CC BY 4.0); robots.txt: Crawl-delay 10, none of these
# paths disallowed (see config/sources/ar-infoleg.yaml). Generated by `python -m scripts.build_infoleg_manifest`.
#
{scale}
"""
PILOT = """laws:
  - {id: 804, text: original, title: Constitución de la Nación Argentina}      # Ley 24.430 (texto oficial, reforma de 1994)
  - {id: 235975, text: actualizado, title: Código Civil y Comercial de la Nación}  # Ley 26.994, Anexo I
  - {id: 16546, text: actualizado, title: Código Penal}                         # Ley 11.179 (t.o. 1984 actualizado)
  - {id: 64790, text: actualizado, title: Ley de Protección de los Datos Personales}  # Ley 25.326
  - {id: 25552, text: actualizado, title: Ley de Contrato de Trabajo}            # Ley 20.744 (t.o. 1976)
  - {id: 22363, text: actualizado, title: Ley de Procedimientos Administrativos}  # Ley 19.549
"""
PILOT_IDS = {804, 235975, 16546, 64790, 25552, 22363}


_CONTROL = re.compile("[\x00-\x08\x0b-\x1f\x7f-\x9f]")


def _clean(value: str) -> str:
    """Drop control characters (the CSV has stray C1 characters from a bad encoding in a few notes); YAML forbids them.
    Only metadata passes through here, never the text of a law."""
    return _CONTROL.sub("", value).strip()


def main() -> int:
    http = PoliteHttp(
        CACHE,
        USER_AGENT,
        allowed_hosts={"datos.jus.gob.ar", "datos.gob.ar"},
        crawl_delay=CRAWL_DELAY,
        timeout=900.0,
    )
    for host in ("datos.gob.ar", "datos.jus.gob.ar"):
        http.get(f"https://{host}/robots.txt")
    got = http.get(ZIP_URL, cache_key=ZIP_KEY)
    if got is None:
        raise SystemExit("the dataset zip was not found")
    data, meta = got
    digest = hashlib.sha256(data).hexdigest()
    rows: list[dict[str, str]] = []
    total = 0
    types: Counter[str] = Counter()
    csv.field_size_limit(1 << 30)
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        name = next(n for n in archive.namelist() if n.endswith(".csv"))
        with archive.open(name) as raw:
            for row in csv.DictReader(io.TextIOWrapper(raw, encoding="utf-8", newline="")):
                total += 1
                types[row["tipo_norma"]] += 1
                if row["tipo_norma"] == "Ley":
                    rows.append(row)
    with_text = [r for r in rows if r["texto_original"] or r["texto_actualizado"]]
    no_number = [r for r in with_text if not re.fullmatch(r"\d{1,6}", r["numero_norma"])]
    laws = [r for r in with_text if r not in no_number and int(r["id_norma"]) not in PILOT_IDS]
    numbers = Counter(r["numero_norma"] for r in laws) + Counter(
        r["numero_norma"] for r in rows if int(r["id_norma"]) in PILOT_IDS
    )
    laws.sort(key=lambda r: (r["fecha_sancion"], int(r["id_norma"])))
    updated = sum(1 for r in with_text if r["texto_actualizado"] and r not in no_number)
    flagged = sum(1 for r in laws if re.search(r"(?i)abrogad|derogad", r["observaciones"]))
    plain_modified = sum(1 for r in laws if not r["texto_actualizado"] and r["modificada_por"] not in ("", "0"))
    requests = len(laws) + 2 * len(PILOT_IDS)
    scale = "\n".join(
        f"# {line}"
        for line in [
            f"Source list: {DATASET_PAGE} - zip {ZIP_URL.rsplit('/', 1)[1]}",
            f"(Last-Modified {meta.get('last_modified')}, retrieved {meta['retrieved_at'][:10]}, sha256 {digest});",
            f"{total:,} norms of which {types['Ley']:,} are 'Ley'.",
            f"Listed: {len(laws) + len(PILOT_IDS):,} laws with a text ({updated:,} with a texto actualizado, the rest the",
            f"original), {requests:,} requests at {CRAWL_DELAY} s = {requests * CRAWL_DELAY / 3600:.1f} h.",
            f"Not listed: {len(rows) - len(with_text):,} laws for which the CSV links no text, {len(no_number)} laws without",
            f"a number (S/N). {plain_modified:,} listed laws were modified (modificada_por) but have only the original text;",
            f"{flagged} have an observation about abrogation.",
            "Size, from a uniform random sample of 70 listed laws (2026-10-15): 68 read, 2 skipped (no numbered article; an image in the text),",
            "~10.6 provision versions per law read (median 3), so ~86,000 in all and ~0.3 GB of",
            "PostgreSQL; raw bundles ~49 KB per law, ~0.4 GB in the object store.",
        ]
    )
    lines = [
        HEADER.format(scale=scale).rstrip("\n"),
        "schema_version: 1",
        "source_id: ar-infoleg",
        "base_url: https://www.argentina.gob.ar",
        f'user_agent: "{USER_AGENT}"',
        f"crawl_delay_seconds: {CRAWL_DELAY}",
        "dataset:",
        f"  record: {DATASET_PAGE}",
        f"  file: {ZIP_URL}",
        f"  last_modified: {json.dumps(meta.get('last_modified'))}",
        f"  retrieved: {json.dumps(meta['retrieved_at'][:10])}",
        f"  sha256: {digest}",
        PILOT.rstrip("\n"),
    ]
    for r in laws:
        entry: dict[str, Any] = {
            "id": int(r["id_norma"]),
            "text": "actualizado" if r["texto_actualizado"] else "original",
            "title": _clean(r["titulo_resumido"]) or f"Ley {r['numero_norma']}",
        }
        if numbers[r["numero_norma"]] > 1:
            entry["number_ambiguous"] = True
        row = {k: _clean(r[k]) for k in KEEP if _clean(r[k]) != ""}
        entry["dataset_row"] = row
        lines.append("  - " + json.dumps(entry, ensure_ascii=False))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # The file must be valid YAML with the entries as written.
    loaded = yaml.safe_load(OUT.read_text(encoding="utf-8"))
    assert len(loaded["laws"]) == len(laws) + len(PILOT_IDS)
    print(
        f"{len(loaded['laws'])} laws written ({updated} updated texts, {len(no_number)} S/N left out), {requests} requests"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Write config/manifests/nl-bwb.yaml from the publisher's sitemap of the Basiswettenbestand.

    python scripts/build_bwb_manifest.py

KOOP gives the Basiswettenbestand (BWB) out in two ways: a base set on request through a contact form (about 14 GB
zipped, once a month), and per-regulation downloads from the open-data repository. The repository has no index of its
own (``/bwb/`` redirects to a description of the service) and the SRU search service
(``zoekservice.overheid.nl``) disallows all robots, so neither lists the regulations. The one public list is the
sitemap that ``wetten.overheid.nl/robots.txt`` declares for crawlers that are not blocked by name
(``https://wetten.overheid.nl/sitemap.xml``: one file, one request, about 47,000 regulation addresses
``https://wetten.overheid.nl/BWBR0001840/``). ULIS asks for that one file with its identifying User-Agent and a 30 s
delay, and does not fetch any page of the website. The BWB identifier is the path segment; the repository serves
``https://repository.officiele-overheidspublicaties.nl/bwb/<BWB id>/manifest.xml`` and the toestand files.

* ``BWBR`` identifiers (regelingen: wetten, AMvB's, ministeriele regelingen, ...) are listed, one current toestand each;
  the six pilot regulations keep their history setting. ``BWBV`` (treaties) and ``BWBW`` identifiers are left out.
* A regulation that has lapsed is not told apart in the sitemap; the connector reads its manifest and skips it.
"""

from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

from ulis.sources.connectors.polite_http import PoliteHttp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "manifests" / "nl-bwb.yaml"
USER_AGENT = "ULIS-research-bot/0.1 (+https://github.com/CHEDFOX/Blue-Cat-Backend)"
HOST = "wetten.overheid.nl"
SITEMAP = f"https://{HOST}/sitemap.xml"
_LOC = re.compile(rf"<loc>https://{re.escape(HOST)}/(BWB[A-Z]\d{{7}})/?</loc>")
PILOT = """\
  - {bwb_id: BWBR0001840, title: Grondwet, history: true}  # constitutional, 11 toestanden since 2002
  - {bwb_id: BWBR0040940, title: Uitvoeringswet Algemene verordening gegevensbescherming, history: true}  # 6 toestanden
  - {bwb_id: BWBR0002656, title: Burgerlijk Wetboek Boek 1, history: false}  # persons and family law
  - {bwb_id: BWBR0005289, title: Burgerlijk Wetboek Boek 6, history: false}  # obligations, tort
  - {bwb_id: BWBR0001854, title: Wetboek van Strafrecht, history: false}  # criminal law
  - {bwb_id: BWBR0005537, title: Algemene wet bestuursrecht, history: false}  # administrative law
"""
HEADER = """# Dutch national regulations fetched from the Basiswettenbestand open-data repository (CC0 1.0).
# For each regulation the connector reads https://repository.officiele-overheidspublicaties.nl/bwb/<bwb_id>/manifest.xml
# and downloads <bwb_id>/<toestand>/xml/<bwb_id>_<toestand>.xml: every toestand that had started when the manifest
# was generated (`history: true`, oldest first) or only the current one (`history: false`). Scheduled toestanden are
# never fetched; the manifest itself is ingested last as a change report. A regulation that has lapsed (its last
# toestand has ended) is skipped after its manifest has been read.
# Generated by scripts/build_bwb_manifest.py from the sitemap https://wetten.overheid.nl/sitemap.xml (one request;
# read {built}): {count} regulations (BWBR identifiers; {treaties} treaties (BWBV) and {other} others are not listed).
# The six pilot regulations come first; the rest follow by identifier.
# Scale: one request for the manifest of every regulation and one for the current toestand of those in force. In a
# random sample of 319 of them 58% had lapsed (manifest only), 31% were an Act, AMvB or ministerial regulation in
# force, 9% another kind (their toestand is read and dropped) and 1% had no toestand in force yet: about 61,000
# requests, about 85 hours at one request per 5 s, for about 13,600 regulations stored (96 provision versions each on
# average, about 3 GB of database).
"""


def main() -> int:
    http = PoliteHttp(ROOT / "var" / "sources", USER_AGENT, allowed_hosts={HOST}, crawl_delay=30.0, timeout=300)
    got = http.get(SITEMAP)
    if got is None:
        raise SystemExit("the sitemap is not served")
    text = got[0].decode("utf-8")
    ids = _LOC.findall(text)
    regulations = sorted({i for i in ids if i.startswith("BWBR")})
    treaties = len({i for i in ids if i.startswith("BWBV")})
    other = len({i for i in ids if not i.startswith(("BWBR", "BWBV"))})
    pilot = re.findall(r"bwb_id: (BWBR\d{7})", PILOT)
    missing = [p for p in pilot if p not in regulations]
    if missing:
        raise SystemExit(f"pilot regulations missing from the sitemap: {missing}")
    rest = [i for i in regulations if i not in pilot]
    header = HEADER.format(
        built=date.today().isoformat(),
        count=len(regulations),
        treaties=treaties,
        other=other,
    )
    lines = ["schema_version: 1", "source_id: nl-bwb"]
    lines += [
        "base_url: https://repository.officiele-overheidspublicaties.nl/bwb",
        f'user_agent: "{USER_AGENT}"',
        "crawl_delay_seconds: 5",
        "regulations:",
    ]
    body = "\n".join(lines) + "\n" + PILOT + "".join(f"  - {{bwb_id: {i}, history: false}}\n" for i in rest)
    OUT.write_text(header + body, encoding="utf-8")
    print(f"{len(regulations)} regulations in the manifest ({treaties} treaties and {other} others not listed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
